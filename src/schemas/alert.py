"""Pydantic schemas for alert ingestion and structured LLM triage responses."""

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class IncomingAlert(BaseModel):
    """Payload model for alerts ingested into the SRE triage system."""

    model_config = ConfigDict(extra="allow")

    service_name: str = Field(
        ...,
        description="Name of the impacted service reporting the alert",
        examples=["payment-gateway"],
    )
    error_message: str = Field(
        ...,
        description="High-level error or exception description",
        examples=[
            "Database connection pool exhausted: timeout waiting for idle connection"
        ],
    )
    raw_logs: dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary diagnostic log dictionary and contextual telemetry",
        examples=[
            {"log_level": "ERROR", "trace_id": "8f3b20e4", "host": "ip-10-0-2-15"}
        ],
    )

    def generate_signature(self) -> str:
        """
        Generate SHA-256 deduplication signature based on service_name and error_message prefix.
        Ensures identical recurring alerts generate the same hash.
        """
        import hashlib

        raw_key = f"{self.service_name}:{self.error_message[:100]}"
        return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()


class LLMTriageResult(BaseModel):
    """Structured LLM triage diagnosis generated by Google Gemini."""

    root_cause_analysis: str = Field(
        ...,
        description="A concise explanation of why the system failed based on the logs.",
    )
    severity_level: Literal["High", "Medium", "Low"] = Field(
        ...,
        description="Strictly constrained to either 'High', 'Medium', or 'Low'.",
    )
    remediation_runbook: list[str] = Field(
        ...,
        description="A step-by-step list of actionable commands or checks for the on-call engineer.",
    )


class AlertTriageResponse(BaseModel):
    """Response returned upon successful ingestion and ticketing."""

    status: str = Field(
        default="ticket_created",
        description="Status of the triage operation",
        examples=["ticket_created"],
    )
    issue_key: str = Field(
        ...,
        description="Jira issue key created for this alert",
        examples=["KAN-102"],
    )
    issue_id: str | None = Field(
        default=None,
        description="Internal Jira issue identifier",
        examples=["10002"],
    )
    issue_url: str | None = Field(
        default=None,
        description="Direct REST or web URL for the created ticket",
        examples=["https://your-name.atlassian.net/rest/api/3/issue/10002"],
    )
    summary: str = Field(
        ...,
        description="Generated summary title for the Jira ticket",
        examples=[
            "[High] Triage: payment-gateway - Database connection pool exhausted"
        ],
    )
    triage_result: LLMTriageResult | None = Field(
        default=None,
        description="Structured LLM analysis with root cause and remediation runbook",
    )
